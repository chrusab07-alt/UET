const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

function loadData() {
  return vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../js/data.js'), 'utf8') + '\nUET_DATA');
}

// Audit only: never coerce, replace, filter, or otherwise alter recommendation data.
function validateStopCoordinates(stop) {
  const issues = [];
  for (const [field, limit] of [['lat', 90], ['lng', 180]]) {
    const value = stop?.[field];
    if (value === undefined || value === null || value === '') issues.push(`${field}: missing`);
    else if (typeof value !== 'number' || !Number.isFinite(value)) issues.push(`${field}: must be a finite number`);
    else if (value < -limit || value > limit) issues.push(`${field}: outside [-${limit}, ${limit}]`);
  }
  return issues;
}

function auditStopCoordinates(routes) {
  const invalidCoordinates = [];
  const invalidMetadata = [];
  const groups = new Map();
  let stopCount = 0;
  for (const route of routes) {
    route.stops.forEach((stop, stopIndex) => {
      stopCount++;
      const reference = { routeId: route.id, routeNo: route.routeNo, campusId: route.campusId, stopIndex, name: stop.name };
      const issues = validateStopCoordinates(stop);
      if (issues.length) invalidCoordinates.push({ ...reference, issues });
      const metadataIssues = [];
      if (!['verified', 'approximate', 'unverified'].includes(stop.coordinateStatus)) metadataIssues.push('invalid coordinateStatus');
      if (stop.placeId !== null && (typeof stop.placeId !== 'string' || !stop.placeId.trim())) metadataIssues.push('placeId must be null or a nonempty string');
      if (stop.source !== null && (typeof stop.source !== 'string' || !stop.source.trim())) metadataIssues.push('source must be null or a nonempty citation string');
      if (!Array.isArray(stop.aliases) || stop.aliases.some(alias => typeof alias !== 'string' || !alias.trim())) metadataIssues.push('aliases must be an array of nonempty strings');
      if (stop.coordinateStatus === 'verified' && !stop.source) metadataIssues.push('verified coordinates require a source');
      if (metadataIssues.length) invalidMetadata.push({ ...reference, issues: metadataIssues });
      if (issues.length) return;
      const key = `${stop.lat},${stop.lng}`;
      if (!groups.has(key)) groups.set(key, { lat: stop.lat, lng: stop.lng, stops: [] });
      groups.get(key).stops.push(reference);
    });
  }
  const duplicateCoordinates = [...groups.values()].filter(group => group.stops.length > 1).map(group => {
    const names = new Set(group.stops.map(stop => stop.name.trim().toLowerCase().replace(/\s+/g, ' ')));
    const routeIds = group.stops.map(stop => stop.routeId);
    const reasons = [];
    if (names.size > 1) reasons.push('Different stop names share exact coordinates');
    if (new Set(routeIds).size < routeIds.length) reasons.push('Coordinates repeated within the same route');
    return { ...group, suspicious: reasons.length > 0, reasons };
  });
  return { routeCount: routes.length, stopCount, invalidCoordinates, invalidMetadata, duplicateCoordinates };
}

function formatAuditReport(report) {
  const suspicious = report.duplicateCoordinates.filter(group => group.suspicious);
  const lines = ['# Stop coordinate audit', '',
    'Generated by `node scripts/audit-stop-coordinates.cjs --write`. No coordinates were verified, corrected, rounded, or inferred.', '',
    `- Routes: ${report.routeCount}`,
    `- Stop records: ${report.stopCount}`,
    `- Invalid/missing coordinate records: ${report.invalidCoordinates.length}`,
    `- Invalid metadata records: ${report.invalidMetadata.length}`,
    `- Exact duplicate coordinate groups: ${report.duplicateCoordinates.length}`,
    `- Suspicious groups for manual review: ${suspicious.length}`, '',
    'Repeated coordinates can be legitimate shared stops or campus terminals. A group is flagged when different names share coordinates (ignoring case/whitespace), or a route repeats those coordinates. These are review candidates, not confirmed errors. No deduplication is performed.', '',
    '## Invalid records', ''];
  const invalid = [...report.invalidCoordinates, ...report.invalidMetadata];
  lines.push(...(invalid.length ? invalid.map(x => `- ${x.routeId}, stop ${x.stopIndex + 1} (${x.name}): ${x.issues.join('; ')}`) : ['None.']));
  lines.push('', '## Suspicious duplicate coordinates', '');
  suspicious.forEach(group => {
    lines.push(`### ${group.lat}, ${group.lng}`, '', group.reasons.join('; ') + '.', '');
    group.stops.forEach(stop => lines.push(`- ${stop.routeId}, stop ${stop.stopIndex + 1}: ${stop.name} (${stop.campusId})`));
    lines.push('');
  });
  lines.push('## Repeated coordinates with the same stop name across routes', '',
    'These groups are retained and listed for completeness; repetition alone is not treated as an error.', '');
  report.duplicateCoordinates.filter(group => !group.suspicious).forEach(group => {
    lines.push(`- ${group.lat}, ${group.lng}: ${group.stops[0].name} — ${group.stops.map(stop => `${stop.routeId} stop ${stop.stopIndex + 1}`).join(', ')}`);
  });
  return lines.join('\n') + '\n';
}

if (require.main === module) {
  const report = auditStopCoordinates(loadData().routes);
  if (process.argv.includes('--write')) {
    fs.mkdirSync(path.join(__dirname, '../docs'), {recursive: true});
    fs.writeFileSync(path.join(__dirname, '../docs/stop-coordinate-audit.md'), formatAuditReport(report));
  }
  console.log(JSON.stringify({routes: report.routeCount, stops: report.stopCount,
    invalidCoordinates: report.invalidCoordinates.length, invalidMetadata: report.invalidMetadata.length,
    duplicateGroups: report.duplicateCoordinates.length,
    suspiciousGroups: report.duplicateCoordinates.filter(group => group.suspicious).length}));
  if (report.invalidCoordinates.length || report.invalidMetadata.length) process.exitCode = 1;
}
module.exports = {loadData, validateStopCoordinates, auditStopCoordinates, formatAuditReport};